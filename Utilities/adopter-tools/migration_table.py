#!/usr/bin/env python3
"""Write the per-file Darwin inventory of a migration into its MIGRATION.md.

Usage: migration_table.py [--stdout] [--max-names N] BASELINE.json CURRENT.json MIGRATION.md

Both JSON files come from `darwin_audit.py --json`: one of the package before the migration (its
merge base, built and audited), one now. The block it writes replaces whatever is between
`<!-- inventory:begin -->` and `<!-- inventory:end -->` in MIGRATION.md, or is appended when
those markers are missing. It has a table of files per top-level directory (unmigrated at the
start and now, SYSTEM-GAP only now) and one row per file that wasn't clean at either end, with the
Darwin names it used (at most --max-names, default 40, each). Unmigrated means `import` or `leak`
in the audit's terms. --stdout prints the block instead of writing the file.
"""

import argparse
import json
import sys

LABEL = {"import": "imports Darwin", "gap": "SYSTEM-GAP only", "leak": "leaks Darwin",
         "fields": "C fields only", "not built": "not built", "clean": "clean"}
BEGIN, END = "<!-- inventory:begin -->", "<!-- inventory:end -->"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("baseline")
    ap.add_argument("current")
    ap.add_argument("migration", metavar="MIGRATION.md")
    ap.add_argument("--stdout", action="store_true", help="print the block instead of writing MIGRATION.md")
    ap.add_argument("--max-names", type=int, default=40)
    a = ap.parse_args()
    with open(a.baseline) as h:
        base = json.load(h)["files"]
    with open(a.current) as h:
        cur_doc = json.load(h)
    cur = cur_doc["files"]

    def area(f):
        return f.split("/")[0] if "/" in f else "."

    def names(v):
        n = [x for x in v.get("names", []) or v.get("fieldNames", []) if x != "Darwin"]
        more = f" … ({len(n) - a.max_names} more)" if len(n) > a.max_names else ""
        return ", ".join(f"`{x}`" for x in n[:a.max_names]) + more

    files = sorted(set(base) | set(cur))
    counts = {}
    for f in files:
        b = base.get(f, {}).get("status", "clean")
        c = cur.get(f, {}).get("status", "clean")
        k = counts.setdefault(area(f), {"start": 0, "now": 0, "gap": 0})
        k["start"] += b in ("import", "leak")
        k["now"] += c in ("import", "leak")
        k["gap"] += c == "gap"
    reexporters = ", ".join(cur_doc.get("reexporters", [])) or "none now"
    lines = [BEGIN, "",
             "Generated by swift-system's `Utilities/adopter-tools/migration_table.py` from two `darwin_audit.py` runs",
             "(compiler-resolved: the index store of a debug build). *imports Darwin*: an import of Darwin in any form,",
             f"or of a module that re-exports it ({reexporters}). *leaks Darwin*: no import, but names written in the",
             "file resolve to Darwin, through another module's re-export. *SYSTEM-GAP only*: every Darwin import left",
             "is a narrow one under a `// SYSTEM-GAP:` marker that accounts for every Darwin name the file uses.",
             "*C fields only*: its only Darwin names are fields of structs it names another way. *not built*: the",
             "build compiled no unit of it.", "",
             "| Area | Unmigrated at start | Unmigrated now | SYSTEM-GAP only now |",
             "|---|---:|---:|---:|"]
    for ar in sorted(counts):
        c = counts[ar]
        lines.append(f"| {ar} | {c['start']} | {c['now']} | {c['gap']} |")
    lines += ["", "| File | Start | Now | Darwin names at start | Darwin names now |", "|---|---|---|---|---|"]
    for f in files:
        b, c = base.get(f, {}), cur.get(f, {})
        bs, cs = b.get("status", "clean"), c.get("status", "clean")
        if bs == "clean" and cs == "clean":
            continue
        lines.append(f"| `{f}` | {LABEL.get(bs, bs)} | {LABEL.get(cs, cs)} | {names(b) if b else ''} | "
                     f"{names(c) if c else ''} |")
    lines += ["", END]
    block = "\n".join(lines)
    summary = ", ".join(f"{ar} {c['start']}→{c['now']} (+{c['gap']} gap)" for ar, c in sorted(counts.items()))
    if a.stdout:
        print(block)
        print(summary, file=sys.stderr)
        return
    try:
        with open(a.migration) as h:
            doc = h.read()
    except FileNotFoundError:
        doc = ""
    if BEGIN in doc and END in doc:
        doc = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    else:
        doc = doc.rstrip("\n") + "\n\n" + block + "\n"
    with open(a.migration, "w") as h:
        h.write(doc)
    print(f"wrote {a.migration}: {summary}")


if __name__ == "__main__":
    main()
